// The website's lint: Next's own rules (core web vitals, React, hooks,
// accessibility, imports) and its TypeScript set, in ESLint's flat format.
//
//   pnpm lint
//
// `next lint` was the script, with no configuration behind it: it stopped at
// an interactive "how would you like to configure ESLint?" and nothing was
// ever linted, by hand, by the build or by CI. eslint-config-next 15 ships in
// the older format, hence FlatCompat — what create-next-app 15 generates.
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FlatCompat } from '@eslint/eslintrc';

const compat = new FlatCompat({ baseDirectory: dirname(fileURLToPath(import.meta.url)) });

const config = [
  {
    ignores: [
      // Built output, dependencies, and the iOS app, which has its own
      // ESLint (mobile/eslint.config.js) and its own install.
      '.next/**',
      '.next-*/**',
      'node_modules/**',
      'mobile/**',
      'next-env.d.ts',
      // Generated by `supabase gen types`.
      'src/lib/supabase/database.types.ts',
    ],
  },
  ...compat.extends('next/core-web-vitals', 'next/typescript'),
  {
    rules: {
      // `_name` is how this codebase says "deliberately unused".
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_', caughtErrorsIgnorePattern: '^_' },
      ],
      // `let [{ data }, { count }] = …` where `data` is reassigned later: a
      // destructuring is const only when every name in it can be.
      'prefer-const': ['error', { destructuring: 'all' }],
    },
  },
  {
    // Tooling and tests that run under Node, not in the app.
    files: ['scripts/**/*.mjs', 'supabase/tests/**/*.mjs', 'load/**/*.js', '*.mjs'],
    rules: {
      // Not React: a function named useX in a script is not a hook.
      'react-hooks/rules-of-hooks': 'off',
    },
  },
];

export default config;
